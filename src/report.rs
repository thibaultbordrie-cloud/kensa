//! Output formats: plain text for the terminal, Markdown for a pull request, JSON for tools.

use std::fmt::Write;

use crate::rules::{rule, Finding, Severity, RULES};

pub fn text(origin: &str, pages: usize, findings: &[Finding]) -> String {
    let mut s = String::new();
    let count = |sev| findings.iter().filter(|f| f.severity == sev).count();
    let _ = writeln!(s, "Kensa 検査 · {origin} · {pages} pages");
    let _ = writeln!(
        s,
        "{} errors · {} warnings · {} notices\n",
        count(Severity::Error),
        count(Severity::Warning),
        count(Severity::Notice)
    );
    for f in findings {
        let tag = match f.severity {
            Severity::Error => "ERROR  ",
            Severity::Warning => "WARNING",
            Severity::Notice => "notice ",
        };
        let _ = writeln!(s, "{tag} {:<28} {}\n        {}", f.rule, f.url, f.message);
    }
    s
}

pub fn markdown(origin: &str, pages: usize, findings: &[Finding]) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# Kensa report\n\n`{origin}` · {pages} pages crawled · {} findings\n", findings.len());
    let _ = writeln!(s, "| Severity | Rule | URL | Detail |\n|---|---|---|---|");
    for f in findings {
        let sev = format!("{:?}", f.severity).to_lowercase();
        let detail = f.message.replace('|', "\\|");
        let _ = writeln!(s, "| {sev} | `{}` | `{}` | {detail} |", f.rule, f.url);
    }
    s
}

/// The rule catalogue as a Markdown table (docs/RULES.md is generated from it).
pub fn rules_markdown() -> String {
    let mut s = String::from(
        "# Rules\n\nGenerated by `kensa rules --markdown`. Severity `notice` is information only and is not scored.\n",
    );
    let mut category = "";
    for r in RULES {
        if r.category != category {
            category = r.category;
            let _ = writeln!(s, "\n## {category}\n\n| Rule | Severity | What it means |\n|---|---|---|");
        }
        let sev = format!("{:?}", rule(r.id).severity).to_lowercase();
        let _ = writeln!(s, "| `{}` | {sev} | {} |", r.id, r.summary.replace('|', "\\|"));
    }
    s
}
